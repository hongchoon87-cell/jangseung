// Writes the compiled AgentVault ABI into the agent's source tree as a typed constant,
// so the agent always talks to the contract with the ABI that was actually compiled.
// Run with `npm run build` (after `hardhat build`).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = path.join(root, "artifacts/contracts/AgentVault.sol/AgentVault.json");
const outDir = path.join(root, "agent/src/abi");
const outPath = path.join(outDir, "agentVault.ts");

const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as { abi: unknown[]; bytecode: string };

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outPath,
  [
    "// Generated by scripts/export-abi.ts from the compiled contract. Do not edit by hand.",
    `export const agentVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;`,
    "",
  ].join("\n"),
);

console.log(`Wrote ${path.relative(root, outPath)} (${artifact.abi.length} ABI entries)`);
